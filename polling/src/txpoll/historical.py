def _pair(labels, abbott, hinojosa, dimension, definition=None):
    rows = []
    for label, a, b in zip(labels, abbott, hinojosa):
        for candidate, party, pct in (
            ("Greg Abbott", "Republican", a),
            ("Gina Hinojosa", "Democrat", b),
        ):
            rows.append(
                {
                    "dimension": dimension,
                    "subgroup": label,
                    "candidate": candidate,
                    "party": party,
                    "percentage": pct,
                    "subgroup_n": None,
                    "definition": definition,
                    "notes": "Subgroup sample size not reported.",
                }
            )
    return rows


