def _src(tier, source_type, url, publisher, publication, primary, notes):
    return {
        "tier": tier,
        "source_type": source_type,
        "url": url,
        "publisher": publisher,
        "publication_date": publication,
        "is_primary": primary,
        "notes": notes,
    }


def _poll(**kwargs):
    results = []
    symbols = kwargs.pop("symbol_map", {})
    for candidate, party, pct, result_type in kwargs.pop("results"):
        results.append(
            {
                "candidate": candidate,
                "party": party,
                "percentage": pct,
                "reported_symbol": symbols.get(candidate),
                "result_type": result_type,
                "result_frame": "headline",
            }
        )
    record = {
        "external_key": kwargs["external_key"],
        "pollster": kwargs["pollster"],
        "pollster_canonical": kwargs["canonical"],
        "pollster_parent_company": kwargs.get("parent"),
        "sponsor": kwargs.get("sponsor"),
        "sponsor_type": kwargs.get("sponsor_type") or "unknown",
        "release_date": kwargs.get("release"),
        "field_start": kwargs.get("start"),
        "field_end": kwargs.get("end"),
        "sample_size": kwargs.get("n"),
        "sample_size_provenance": kwargs.get("n_note"),
        "sample_type": kwargs.get("sample_type"),
        "mode": kwargs.get("mode") or [],
        "reported_moe": kwargs.get("moe"),
        "design_effect_moe": kwargs.get("design_moe"),
        "moe_kind": kwargs.get("moe_kind"),
        "confidence_level": 0.95,
        "ballot_configuration": kwargs.get("ballot"),
        "ballot_flags": kwargs.get("flags") or [],
        "question_wording": kwargs.get("wording"),
        "population_description": kwargs.get("population"),
        "weighting_description": kwargs.get("weighting"),
        "state": "TX",
        "race": "Governor",
        "cycle": 2026,
        "approved_for_model": bool(kwargs.get("approved")),
        "auto_confidence": kwargs.get("confidence"),
        "results": results,
        "sources": kwargs.get("sources") or [],
        "methodology_text": kwargs.get("methodology"),
        "panel_provider": kwargs.get("panel"),
        "subgroups": kwargs.get("subgroups") or [],
        "extraction_warnings": kwargs.get("warnings") or [],
        "notes": kwargs.get("notes"),
        "alternate_frames": kwargs.get("alternate") or [],
        "duplicate_aliases": kwargs.get("duplicate_aliases") or [],
        "local_file_path": kwargs.get("local_note"),
    }
    return record
